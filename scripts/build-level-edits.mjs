// Turns Level Maker exports in data/levels/<level-id>.json into js/level-edits.js,
// which levels.js applies as the built-in layout of those levels.
// Run after exporting a level from the Level Maker: node scripts/build-level-edits.mjs
import { readdir, readFile, writeFile } from 'node:fs/promises';

const dir = new URL('../data/levels/', import.meta.url);
const edits = {};
for (const file of (await readdir(dir)).filter(f => f.endsWith('.json')).sort()) {
  const data = JSON.parse(await readFile(new URL(file, dir), 'utf8'));
  edits[file.slice(0, -5)] = {
    canvas: data.canvas,
    // The maker calls it gameLocked; the game calls it locked.
    elements: data.elements.map(({ gameLocked, ...el }) => ({ ...el, locked: !!gameLocked })),
  };
}
await writeFile(new URL('../js/level-edits.js', import.meta.url),
  `/* Generated by scripts/build-level-edits.mjs from data/levels/*.json — edit those, not this. */\n` +
  `window.EC_LEVEL_EDITS = ${JSON.stringify(edits)};\n`);
console.log('level edits:', Object.keys(edits).join(', '));
